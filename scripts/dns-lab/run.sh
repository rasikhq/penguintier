#!/usr/bin/env bash
# Tests penguintier-dns-helper ("Enable DNS support…") in disposable
# containers, never on this machine. Each scenario gets a fresh Debian 13
# container where NetworkManager owns eth1 and gets its address and DNS
# server (10.10.0.1) by DHCP from a fake router: dnsmasq in its own network
# namespace, answering check.pt-lab. The helper must leave every scenario
# with names resolving and, when it undoes, with /etc/resolv.conf and
# /etc/nsswitch.conf byte for byte as before.
#
#   scripts/dns-lab/run.sh [scenario...]   default: all of them
#
# Scenarios: enable-undo rollback sigterm crash crash-busy refuse
#
# Needs podman (rootless is fine) and Go. Takes a few minutes. See
# "DNS switch lab" in docs/testing.md.
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../.." && pwd)
image=localhost/penguintier-dns-lab
name=penguintier-dns-lab
work=$(mktemp -d)
trap 'podman rm -f "$name" >/dev/null 2>&1 || true; rm -rf "$work"' EXIT

failures=0
pass() { echo "  PASS  $*"; }
fail() { echo "  FAIL  $*"; failures=$((failures + 1)); }
# check DESCRIPTION COMMAND...: PASS if the command succeeds.
check() {
	local what=$1
	shift
	if "$@"; then pass "$what"; else fail "$what"; fi
}

echo "Building penguintier-dns-helper and the lab image..."
(cd "$repo" && CGO_ENABLED=0 go build -o "$work/penguintier-dns-helper" ./cmd/penguintier-dns-helper)
podman build -q -t "$image" -f "$here/Containerfile" "$here" >/dev/null

# lab COMMAND: runs a shell command as root in the lab.
lab() {
	podman exec -e PENGUINTIER_DNS_CHECK_NAMES=check.pt-lab "$name" sh -c "$1"
}

# start_lab: a fresh container with the fake router and NetworkManager up.
start_lab() {
	podman rm -f "$name" >/dev/null 2>&1 || true
	# --dns=none: podman doesn't mount its own /etc/resolv.conf, so
	# NetworkManager writes it, as on a real machine.
	podman run -d --name "$name" --systemd=always --privileged --dns=none --hostname "$name" "$image" >/dev/null
	sleep 4
	podman cp "$work/penguintier-dns-helper" "$name:/usr/local/sbin/penguintier-dns-helper"
	lab '
set -e
ip netns add router
ip link add eth1 type veth peer name eth-r
ip link set eth-r netns router
R="nsenter --net=/run/netns/router"
$R ip addr add 10.10.0.1/24 dev eth-r
$R ip link set eth-r up
$R ip link set lo up
$R dnsmasq --pid-file=/run/router-dnsmasq.pid --no-resolv --no-hosts --bind-interfaces --interface=eth-r \
  --dhcp-range=10.10.0.100,10.10.0.200,1h --dhcp-option=3 --dhcp-option=6,10.10.0.1 \
  --address=/check.pt-lab/10.10.0.1
systemctl start systemd-udevd
udevadm trigger --action=add --subsystem-match=net
udevadm settle -t 5
systemctl restart NetworkManager
for i in $(seq 1 40); do
  nmcli -t -f DEVICE,STATE dev | grep -q "^eth1:connected$" && grep -q "^# Generated by NetworkManager" /etc/resolv.conf \
    && getent ahosts check.pt-lab >/dev/null 2>&1 && break
  sleep 1
done
mkdir -p /root/before && cp -a /etc/resolv.conf /etc/nsswitch.conf /root/before/
' || { echo "the lab did not come up"; exit 1; }
}

# Assertions about the lab, as functions so check() can run them.
resolves() { lab 'getent ahosts check.pt-lab >/dev/null'; }
files_as_before() { lab 'cmp -s /etc/resolv.conf /root/before/resolv.conf && cmp -s /etc/nsswitch.conf /root/before/nsswitch.conf'; }
resolved_gone() { lab '! dpkg-query -W -f="\${db:Status-Abbrev}" systemd-resolved 2>/dev/null | grep -q "^ii" && test ! -e /etc/systemd/resolved.conf'; }
no_backup() { lab 'test ! -e /var/lib/penguintier/dns-backup'; }
state_is() { lab "test \"\$(jq -r .state /var/lib/penguintier/dns-backup/manifest.json)\" = $1"; }
# helper ARGS EXPECTED-EXIT: runs the helper, keeps its JSON in /tmp/result
# and its log in /tmp/log, and shows both when the exit code is wrong.
helper() {
	lab "penguintier-dns-helper $1 >/tmp/result 2>/tmp/log; code=\$?
	     if [ \$code -ne $2 ]; then echo \"    exit \$code, want $2\"; sed 's/^/    /' /tmp/log /tmp/result; exit 1; fi"
}
result_is() { lab "test \"\$(jq -r .result /tmp/result)\" = $1"; }

scenario_enable-undo() {
	echo "enable-undo: switch on, then back"
	start_lab
	check "check says supported" helper check 0
	check "enable succeeds" helper enable 0
	check "result is enabled" result_is enabled
	check "names resolve through systemd-resolved" resolves
	check "NetworkManager gave resolved its DNS server" lab 'resolvectl dns eth1 | grep -q 10.10.0.1'
	check "nsswitch.conf untouched" lab 'cmp -s /etc/nsswitch.conf /root/before/nsswitch.conf'
	check "manifest says enabled" state_is enabled
	check "undo succeeds" helper undo 0
	check "files byte for byte as before" files_as_before
	check "systemd-resolved removed, with its settings" resolved_gone
	check "names resolve" resolves
}

scenario_rollback() {
	echo "rollback: names stop resolving after the switch"
	start_lab
	# Break DNS for systemd-resolved only: drop DNS packets of every user
	# but root. Lookups that root makes directly keep working.
	lab 'nft add table inet ptlab && nft add chain inet ptlab out "{ type filter hook output priority 0; }" &&
	    nft add rule inet ptlab out meta skuid != 0 udp dport 53 drop && nft add rule inet ptlab out meta skuid != 0 tcp dport 53 drop'
	check "enable fails and undoes itself (exit 1)" helper enable 1
	check "result is rolled-back" result_is rolled-back
	check "files byte for byte as before" files_as_before
	check "systemd-resolved removed" resolved_gone
	check "names resolve" resolves
	check "manifest says rolled-back" state_is rolled-back
}

scenario_sigterm() {
	echo "sigterm: stopped in the middle"
	start_lab
	lab 'penguintier-dns-helper enable >/tmp/result 2>/tmp/log & P=$!
	    until grep -q "Waiting for systemd-resolved" /tmp/log; do sleep 0.1; done
	    kill -TERM $P; wait $P; test $? -eq 1'
	check "result is rolled-back" result_is rolled-back
	check "it says it was interrupted" lab 'jq -r .message /tmp/result | grep -q interrupted'
	check "files byte for byte as before" files_as_before
	check "names resolve" resolves
}

scenario_crash() {
	echo "crash: killed during the install, then undo"
	start_lab
	lab 'penguintier-dns-helper enable >/tmp/result 2>/tmp/log & P=$!
	    until grep -q "Installing systemd-resolved" /tmp/log; do sleep 0.05; done
	    kill -KILL $P
	    while pgrep -x apt-get >/dev/null || pgrep -x dpkg >/dev/null; do sleep 0.5; done'
	check "manifest says in-progress" state_is in-progress
	check "check refuses a new switch" helper check 3
	check "and points to undo" lab 'jq -r .message /tmp/result | grep -q "did not finish"'
	check "undo succeeds" helper undo 0
	check "files byte for byte as before" files_as_before
	check "systemd-resolved removed" resolved_gone
	check "names resolve" resolves
}

scenario_crash-busy() {
	echo "crash-busy: killed during the install, undo started at once"
	start_lab
	lab 'penguintier-dns-helper enable >/tmp/result 2>/tmp/log & P=$!
	    until grep -q "Installing systemd-resolved" /tmp/log; do sleep 0.05; done
	    kill -KILL $P'
	check "undo waits for the install, then succeeds" helper undo 0
	check "files byte for byte as before" files_as_before
	check "systemd-resolved removed" resolved_gone
	check "names resolve" resolves
	check "still so 10 s later (no late install)" lab 'sleep 10; getent ahosts check.pt-lab >/dev/null && cmp -s /etc/resolv.conf /root/before/resolv.conf'
}

scenario_refuse() {
	echo "refuse: unsupported setups change nothing"
	start_lab
	lab 'printf "nameserver 10.10.0.1\n" > /etc/resolv.conf'
	check "hand-written resolv.conf: refused (exit 3)" helper enable 3
	check "  and nothing was changed" no_backup
	lab 'cp /root/before/resolv.conf /etc/resolv.conf'
	check "no working DNS: refused" lab 'PENGUINTIER_DNS_CHECK_NAMES=nothing.invalid penguintier-dns-helper enable >/dev/null 2>&1; test $? -eq 3'
	check "  and nothing was changed" no_backup
	lab 'systemctl stop NetworkManager'
	check "NetworkManager stopped: refused" helper enable 3
	check "  and nothing was changed" no_backup
	check "  and resolved was not installed" resolved_gone
}

scenarios=("$@")
if [ ${#scenarios[@]} -eq 0 ]; then
	scenarios=(enable-undo rollback sigterm crash crash-busy refuse)
fi
for s in "${scenarios[@]}"; do
	"scenario_$s"
done

echo
if [ "$failures" -eq 0 ]; then
	echo "All DNS lab checks passed."
else
	echo "$failures DNS lab check(s) failed."
	exit 1
fi
