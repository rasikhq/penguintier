package main

import (
	"fmt"
	"os"
	"strings"
)

// section is a group of components with a heading, like "Go modules".
type section struct {
	title      string
	intro      string
	components []component
}

const rule = "--------------------------------------------------------------------------------"
const doubleRule = "================================================================================"

const header = `Third-party licenses of Penguintier
===================================

Penguintier is released under the MIT License (see the LICENSE file in this
folder). Its programs are built from, and ship with, the third-party software
listed below. Each of those components has its own license, and the texts
follow, as those licenses require.

This file is generated by "make third-party-licenses" from the dependencies
that are really built into this package, so it always matches it.
`

// writeFile renders the sections and writes them to path.
func writeFile(path string, sections []section) error {
	// 0o644: this is documentation that every user of the system should be
	// able to read, unlike the secrets gosec worries about.
	if err := os.WriteFile(path, []byte(render(sections)), 0o644); err != nil { //nolint:gosec // a public documentation file
		return fmt.Errorf("write %s: %w", path, err)
	}
	return nil
}

// render builds the whole file: the header, a table of contents, then the
// license text of every component. The output only depends on the input (no
// dates, no random order), so building twice gives the same file.
func render(sections []section) string {
	var b strings.Builder
	b.WriteString(header)

	// Table of contents.
	for _, s := range sections {
		fmt.Fprintf(&b, "\n%s\n", s.title)
		for _, c := range s.components {
			fmt.Fprintf(&b, "  %s (%s)\n", label(c), c.license)
		}
	}

	// The texts.
	for _, s := range sections {
		fmt.Fprintf(&b, "\n\n%s\n%s\n%s\n", doubleRule, s.title, doubleRule)
		if s.intro != "" {
			fmt.Fprintf(&b, "%s\n", s.intro)
		}
		for _, c := range s.components {
			fmt.Fprintf(&b, "\n%s\n%s\nLicense: %s\n", rule, label(c), c.license)
			if c.url != "" {
				fmt.Fprintf(&b, "%s\n", c.url)
			}
			for _, t := range c.texts {
				// Say which file a text came from only when there are
				// several, e.g. LICENSE and NOTICE.
				if len(c.texts) > 1 {
					fmt.Fprintf(&b, "\n[%s]\n", t.file)
				}
				fmt.Fprintf(&b, "\n%s\n", t.text)
			}
		}
	}
	return b.String()
}

// label is the name of a component with its version, e.g. "react 19.3.1".
func label(c component) string {
	if c.version == "" {
		return c.name
	}
	return c.name + " " + c.version
}
