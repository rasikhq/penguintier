func TestGatherFiles(t *testing.T) {
	root, _, _ := testRoot(t)
	writeFile(t, filepath.Join(root, "etc/os-release"), []byte("ID=debian\nPRETTY_NAME=\"Debian GNU/Linux 13 (trixie)\"\n"), 0o644)
	if err := os.MkdirAll(filepath.Join(root, "proc/1"), 0o755); err != nil {
		t.Fatal(err)
	}
	writeFile(t, filepath.Join(root, "proc/1/comm"), []byte("systemd\n"), 0o644)
	t.Setenv(EnvCheckNames, "check.pt-lab, other.pt-lab")

	var asked []string
	f := Gather(t.Context(), Env{
		Root:       root,
		BusAddress: "unix:path=/nonexistent/bus", // no bus: NetworkManager counts as not running
		Lookup: func(_ context.Context, name string) error {
			asked = append(asked, name)
			if name == "other.pt-lab" {
				return nil
			}
			return errors.New("nope")
		},
	})
	if f.OSFamily != "debian" || !f.SystemdPID1 || !f.ResolvConf.GeneratedByNM || f.Packages[PackageResolved] != "not-installed" {
		t.Errorf("facts %+v", f)
	}
	if f.LookupName != "other.pt-lab" || !slices.Equal(asked, []string{"check.pt-lab", "other.pt-lab"}) {
		t.Errorf("lookup name %q after asking %q", f.LookupName, asked)
	}
	if f.NetworkManager || Check(f).OK {
		t.Error("without a system bus the setup must not count as supported")
	}
}
