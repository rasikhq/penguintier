// supported are the facts of the setup Check accepts: a Debian GNOME
// desktop where NetworkManager writes /etc/resolv.conf (the machine this
// was found on).
func supported() Facts {
	return Facts{
		OSFamily:       "debian",
		OSName:         "Debian GNU/Linux 13 (trixie)",
		SystemdPID1:    true,
		AptAvailable:   true,
		Packages:       map[string]string{PackageResolved: "not-installed", packageResolvconf: "not-installed", packageOpenresolv: "not-installed"},
		NetworkManager: true,
		NMMode:         "default",
		NMRcManager:    "symlink",
		ResolvConf:     ResolvConfInfo{Exists: true, GeneratedByNM: true},
		LookupName:     "deb.debian.org",
	}
}

func TestCheck(t *testing.T) {
	tests := []struct {
		name   string
		change func(f *Facts) // nil: supported() as it is
		want   string         // "" = OK; else a piece of the one problem
	}{
		{name: "supported"},
		{name: "resolved removed earlier, settings kept", change: func(f *Facts) { f.Packages[PackageResolved] = "config-files" }},
		{name: "Fedora", change: func(f *Facts) { f.OSFamily, f.OSName = "fedora", "Fedora Linux 42" }, want: "Fedora Linux 42 is not a Debian-family"},
		{name: "no systemd", change: func(f *Facts) { f.SystemdPID1 = false }, want: "systemd is not the init system"},
		{name: "no apt", change: func(f *Facts) { f.AptAvailable = false }, want: "apt-get or dpkg is missing"},
		{name: "resolved installed", change: func(f *Facts) { f.Packages[PackageResolved] = "installed" }, want: "installed already"},
		{name: "resolved running", change: func(f *Facts) { f.ResolvedRunning = true }, want: "running already"},
		{name: "resolvconf", change: func(f *Facts) { f.Packages[packageResolvconf] = "installed" }, want: "resolvconf is installed"},
		{name: "no NetworkManager", change: func(f *Facts) { f.NetworkManager = false }, want: "NetworkManager is not running"},
		{name: "NM uses dnsmasq", change: func(f *Facts) { f.NMMode = "dnsmasq" }, want: `mode is "dnsmasq"`},
		{name: "NM leaves resolv.conf alone", change: func(f *Facts) { f.NMRcManager = "unmanaged" }, want: `rc-manager is "unmanaged"`},
		{name: "networkd", change: func(f *Facts) { f.Networkd = true }, want: "systemd-networkd is running"},
		{name: "no resolv.conf", change: func(f *Facts) { f.ResolvConf = ResolvConfInfo{} }, want: "does not exist"},
		{name: "resolv.conf is a link", change: func(f *Facts) { f.ResolvConf = ResolvConfInfo{Exists: true, Symlink: "/run/resolvconf/resolv.conf"} }, want: "link to /run/resolvconf/resolv.conf"},
		{name: "hand-written resolv.conf", change: func(f *Facts) { f.ResolvConf.GeneratedByNM = false }, want: "not written by NetworkManager"},
		{name: "offline", change: func(f *Facts) { f.LookupName, f.LookupErr = "", errors.New("timed out") }, want: "Name lookups don't work right now (timed out)"},
		{name: "unfinished switch", change: func(f *Facts) { f.Backup = StateInProgress }, want: "did not finish"},
		{name: "already switched", change: func(f *Facts) { f.Backup = StateEnabled }, want: "switched on before"},
		{name: "earlier switch rolled back", change: func(f *Facts) { f.Backup = StateRolledBack }},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			f := supported()
			if tt.change != nil {
				tt.change(&f)
			}
			v := Check(f)
			if tt.want == "" {
				if !v.OK {
					t.Fatalf("refused: %s", v.Text())
				}
				return
			}
			if v.OK || len(v.Problems) != 1 || !strings.Contains(v.Problems[0], tt.want) {
				t.Errorf("verdict %+v, want one problem containing %q", v, tt.want)
			}
			if !strings.Contains(v.Text(), "changed nothing") || !strings.Contains(v.Text(), "keep a copy of /etc/resolv.conf") {
				t.Errorf("Text() lacks the reassurance or the manual way:\n%s", v.Text())
			}
		})
	}
}

// testRoot makes a fake system root with NetworkManager's resolv.conf and
// an nsswitch.conf, and returns it with the original contents.
func testRoot(t *testing.T) (root string, resolv, nsswitch []byte) {
	t.Helper()
	root = t.TempDir()
	for _, dir := range []string{"etc/systemd", "var/lib"} {
		if err := os.MkdirAll(filepath.Join(root, dir), 0o755); err != nil {
			t.Fatal(err)
		}
	}
	resolv = []byte("# Generated by NetworkManager\nnameserver 192.168.18.1\nnameserver fe80::1%wlo1\n")
	nsswitch = []byte("hosts: files myhostname mdns4_minimal [NOTFOUND=return] dns\n")
	writeFile(t, filepath.Join(root, "etc/resolv.conf"), resolv, 0o644)
	writeFile(t, filepath.Join(root, "etc/nsswitch.conf"), nsswitch, 0o644)
	return root, resolv, nsswitch
}

func writeFile(t *testing.T, path string, data []byte, mode os.FileMode) {
	t.Helper()
	if err := os.WriteFile(path, data, mode); err != nil {
		t.Fatal(err)
	}
}

// assertRestored checks that the fake root is exactly as testRoot made it.
func assertRestored(t *testing.T, root string, resolv, nsswitch []byte) {
	t.Helper()
	for path, want := range map[string][]byte{"etc/resolv.conf": resolv, "etc/nsswitch.conf": nsswitch} {
		full := filepath.Join(root, path)
		info, err := os.Lstat(full)
		if err != nil || !info.Mode().IsRegular() || info.Mode().Perm() != 0o644 {
			t.Errorf("%s: %v (err %v), want a regular 0644 file", path, info, err)
			continue
		}
		if got, _ := os.ReadFile(full); string(got) != string(want) {
			t.Errorf("%s = %q, want %q", path, got, want)
		}
	}
	if _, err := os.Lstat(filepath.Join(root, "etc/systemd/resolved.conf")); !errors.Is(err, os.ErrNotExist) {
		t.Errorf("etc/systemd/resolved.conf exists after the undo (err %v); it did not before", err)
	}
}

func TestBackupRestore(t *testing.T) {
	root, resolv, nsswitch := testRoot(t)
	store := Store{Root: root}

	m, err := store.Backup("deb.debian.org")
	if err != nil {
		t.Fatal(err)
	}
	if m.State != StateInProgress || len(m.Files) != len(AffectedFiles) {
		t.Fatalf("manifest %+v", m)
	}
	loaded, err := store.Load()
	if err != nil || loaded == nil || loaded.CheckName != "deb.debian.org" || loaded.Files[0].SHA256 == "" {
		t.Fatalf("Load = %+v, %v", loaded, err)
	}

	// What the package's scripts do: a link instead of the file, a new
	// settings file, an edited nsswitch.conf.
	resolvPath := filepath.Join(root, "etc/resolv.conf")
	if err := os.Remove(resolvPath); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink("../run/systemd/resolve/stub-resolv.conf", resolvPath); err != nil {
		t.Fatal(err)
	}
	writeFile(t, filepath.Join(root, "etc/systemd/resolved.conf"), []byte("[Resolve]\n"), 0o644)
	writeFile(t, filepath.Join(root, "etc/nsswitch.conf"), []byte("hosts: files resolve dns\n"), 0o600)

	if err := store.Restore(loaded); err != nil {
		t.Fatal(err)
	}
	assertRestored(t, root, resolv, nsswitch)
}

func TestRestoreRefusesDamagedCopy(t *testing.T) {
	root, _, _ := testRoot(t)
	store := Store{Root: root}
	m, err := store.Backup("x")
	if err != nil {
		t.Fatal(err)
	}
	writeFile(t, filepath.Join(root, BackupDir, "resolv.conf"), []byte("nameserver 6.6.6.6\n"), 0o644)
	if err := store.Restore(m); err == nil || !strings.Contains(err.Error(), "damaged") {
		t.Errorf("Restore with a changed copy: %v, want a checksum error", err)
	}
}

// behavior decides what works on a fakeSystem. It is its own struct so
// test tables can hold it: a fakeSystem has a mutex, which must not be
// copied.
type behavior struct {
	installErr error
	// race: resolved has no bus name until it is restarted.
	race bool
	// needReload: names resolve through resolved only after
	// `nmcli general reload dns-full`.
	needReload bool
	// neverResolves: names never resolve through resolved.
	neverResolves bool
	// brokenAfterUndo: names don't resolve even after the undo.
	brokenAfterUndo bool
}

// fakeSystem plays the computer. Its file changes copy what the Debian
// package's scripts do; its behavior decides what works.
//
// It embeds behavior: the fields of behavior can be used as if they were
// fakeSystem's own (s.race, s.installErr).
type fakeSystem struct {
	behavior
	root string

	mu                         sync.Mutex
	calls                      []string
	installed, onBus, reloaded bool
}

func (s *fakeSystem) record(call string) {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.calls = append(s.calls, call)
}

func (s *fakeSystem) InstallResolved(context.Context) error {
	s.record("install")
	if s.installErr != nil {
		return s.installErr
	}
	resolv := filepath.Join(s.root, "etc/resolv.conf")
	_ = os.Remove(resolv)
	_ = os.Symlink("../run/systemd/resolve/stub-resolv.conf", resolv)
	_ = os.WriteFile(filepath.Join(s.root, "etc/systemd/resolved.conf"), []byte("[Resolve]\n"), 0o644)
	s.mu.Lock()
	s.installed, s.onBus = true, !s.race
	s.mu.Unlock()
	return nil
}

func (s *fakeSystem) Purge(_ context.Context, packages []string) error {
	s.record("purge " + strings.Join(packages, " "))
	// The removal script: the link becomes a copy of resolved's (empty)
	// server list, and the settings file goes.
	resolv := filepath.Join(s.root, "etc/resolv.conf")
	_ = os.Remove(resolv)
	_ = os.WriteFile(resolv, []byte("search .\n"), 0o644)
	_ = os.Remove(filepath.Join(s.root, "etc/systemd/resolved.conf"))
	s.mu.Lock()
	s.installed, s.onBus = false, false
	s.mu.Unlock()
	return nil
}

func (s *fakeSystem) ResolvedOnBus(context.Context) bool {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.onBus
}

func (s *fakeSystem) RestartResolved(context.Context) error {
	s.record("restart")
	s.mu.Lock()
	s.onBus = s.installed
	s.mu.Unlock()
	return nil
}

func (s *fakeSystem) ReloadNetworkManager(_ context.Context, what string) error {
	s.record("nmcli reload " + what)
	if what == "dns-full" {
		s.mu.Lock()
		s.reloaded = true
		s.mu.Unlock()
	}
	return nil
}

func (s *fakeSystem) Lookup(context.Context, string) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	works := false
	if s.installed {
		works = s.onBus && !s.neverResolves && (!s.needReload || s.reloaded)
	} else {
		// Without resolved, names work when /etc/resolv.conf has a server.
		data, _ := os.ReadFile(filepath.Join(s.root, "etc/resolv.conf"))
		works = strings.Contains(string(data), "nameserver") && !s.brokenAfterUndo
	}
	if !works {
		return errors.New("does not resolve")
	}
	return nil
}

func (s *fakeSystem) allCalls() []string {
	s.mu.Lock()
	defer s.mu.Unlock()
	return slices.Clone(s.calls)
}

// quick are short timeouts, so failing checks don't make the tests slow.
var quick = Timeouts{Bus: 30 * time.Millisecond, Lookup: 30 * time.Millisecond, Retry: 30 * time.Millisecond, Install: time.Second, Poll: 5 * time.Millisecond}

func TestEnable(t *testing.T) {
	tests := []struct {
		name      string
		system    behavior
		facts     func(f *Facts)
		want      string   // outcome
		wantCalls []string // in order
		wantState string   // manifest state afterwards ("" = no manifest)
		restored  bool     // the files must be exactly as before
	}{
		{
			name: "works at once", want: OutcomeEnabled, wantState: StateEnabled,
			wantCalls: []string{"install"},
		},
		{
			name: "Debian race: a restart fixes it", system: behavior{race: true},
			want: OutcomeEnabled, wantState: StateEnabled, wantCalls: []string{"install", "restart"},
		},
		{
			name: "NetworkManager needs a nudge", system: behavior{needReload: true},
			want: OutcomeEnabled, wantState: StateEnabled, wantCalls: []string{"install", "nmcli reload dns-full"},
		},
		{
			name: "names never resolve: everything is undone", system: behavior{neverResolves: true},
			want: OutcomeRolledBack, wantState: StateRolledBack, restored: true,
			wantCalls: []string{"install", "nmcli reload dns-full", "purge systemd-resolved", "nmcli reload dns-rc"},
		},
		{
			name: "install fails: undone", system: behavior{installErr: errors.New("could not get lock")},
			want: OutcomeRolledBack, wantState: StateRolledBack, restored: true,
			wantCalls: []string{"install", "purge systemd-resolved", "nmcli reload dns-rc"},
		},
		{
			name: "undo fails too: manual steps", system: behavior{neverResolves: true, brokenAfterUndo: true},
			want: OutcomeFailed, wantState: StateUndoFailed,
			wantCalls: []string{"install", "nmcli reload dns-full", "purge systemd-resolved", "nmcli reload dns-rc"},
		},
		{
			name: "unsupported setup: nothing touched", facts: func(f *Facts) { f.NetworkManager = false },
			want: OutcomeRefused,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			root, resolv, nsswitch := testRoot(t)
			sys := &fakeSystem{behavior: tt.system, root: root}
			facts := supported()
			if tt.facts != nil {
				tt.facts(&facts)
			}
			var log []string
			sw := Switch{Store: Store{Root: root}, System: sys, Timeouts: quick, Log: func(l string) { log = append(log, l) }}

			res := sw.Enable(t.Context(), facts)
			if res.Outcome != tt.want {
				t.Fatalf("outcome %q (%s), want %q\nlog:\n%s", res.Outcome, res.Message, tt.want, strings.Join(log, "\n"))
			}
			if calls := sys.allCalls(); !slices.Equal(calls, tt.wantCalls) {
				t.Errorf("calls %q, want %q", calls, tt.wantCalls)
			}
			m, err := sw.Store.Load()
			if err != nil {
				t.Fatal(err)
			}
			switch {
			case tt.wantState == "" && m != nil:
				t.Errorf("a manifest was written (%s) although nothing should have changed", m.State)
			case tt.wantState != "" && (m == nil || m.State != tt.wantState):
				t.Errorf("manifest %+v, want state %q", m, tt.wantState)
			}
			if tt.restored {
				assertRestored(t, root, resolv, nsswitch)
			}
			if tt.want == OutcomeFailed && !strings.Contains(res.Message, "sudo dpkg --purge systemd-resolved") {
				t.Errorf("a failed undo must give the manual steps: %s", res.Message)
			}
		})
	}
}

// TestEnableInterrupted: a cancelled context (SIGTERM) still undoes the
// switch completely.
func TestEnableInterrupted(t *testing.T) {
	root, resolv, nsswitch := testRoot(t)
	sys := &fakeSystem{behavior: behavior{race: true}, root: root}
	ctx, cancel := context.WithCancel(t.Context())
	slow := quick
	slow.Bus = time.Second
	sw := Switch{Store: Store{Root: root}, System: sys, Timeouts: slow}

	go func() {
		time.Sleep(50 * time.Millisecond) // while it waits for the bus name
		cancel()
	}()
	res := sw.Enable(ctx, supported())
	if res.Outcome != OutcomeRolledBack || !strings.Contains(res.Message, "interrupted") {
		t.Fatalf("outcome %q: %s", res.Outcome, res.Message)
	}
	assertRestored(t, root, resolv, nsswitch)
}

func TestUndo(t *testing.T) {
	t.Run("after a successful switch", func(t *testing.T) {
		root, resolv, nsswitch := testRoot(t)
		sys := &fakeSystem{root: root}
		sw := Switch{Store: Store{Root: root}, System: sys, Timeouts: quick}
		if res := sw.Enable(t.Context(), supported()); res.Outcome != OutcomeEnabled {
			t.Fatal(res.Message)
		}
		if res := sw.Undo(t.Context()); res.Outcome != OutcomeUndone {
			t.Fatalf("Undo: %q %s", res.Outcome, res.Message)
		}
		assertRestored(t, root, resolv, nsswitch)
		if res := sw.Undo(t.Context()); res.Outcome != OutcomeRefused {
			t.Errorf("a second Undo: %q, want refused", res.Outcome)
		}
	})

	t.Run("after a crash in the middle", func(t *testing.T) {
		root, resolv, nsswitch := testRoot(t)
		sys := &fakeSystem{root: root}
		store := Store{Root: root}
		// The backup was made and the package installed, then the power
		// went out.
		m, err := store.Backup("deb.debian.org")
		if err != nil {
			t.Fatal(err)
		}
		m.Installed = []string{PackageResolved}
		if err := store.Save(m); err != nil {
			t.Fatal(err)
		}
		if err := sys.InstallResolved(t.Context()); err != nil {
			t.Fatal(err)
		}

		sw := Switch{Store: store, System: sys, Timeouts: quick}
		if res := sw.Undo(t.Context()); res.Outcome != OutcomeUndone {
			t.Fatalf("Undo: %q %s", res.Outcome, res.Message)
		}
		assertRestored(t, root, resolv, nsswitch)
	})

	t.Run("nothing to undo", func(t *testing.T) {
		root, _, _ := testRoot(t)
		sw := Switch{Store: Store{Root: root}, System: &fakeSystem{root: root}, Timeouts: quick}
		if res := sw.Undo(t.Context()); res.Outcome != OutcomeRefused {
			t.Errorf("Undo without a backup: %q, want refused", res.Outcome)
		}
	})
}

