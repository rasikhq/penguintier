package dnssetup

import (
	"fmt"
	"strings"
)

// Facts are what Check looks at. Gather reads them from the system.
type Facts struct {
	// OSFamily is watcher.OSRelease.Family(): "debian" for Debian,
	// Ubuntu, Mint and the like.
	OSFamily string
	// OSName is PRETTY_NAME from /etc/os-release, for messages.
	OSName string
	// SystemdPID1: systemd is the init system.
	SystemdPID1 bool
	// AptAvailable: apt-get and dpkg are installed.
	AptAvailable bool
	// Packages is dpkg's state of the packages that matter, by name:
	// "installed", "config-files" (removed, settings kept), or
	// "not-installed".
	Packages map[string]string
	// ResolvedRunning: systemd-resolved runs (its unit is active, or its
	// bus name is owned).
	ResolvedRunning bool
	// NetworkManager: NetworkManager runs; NMMode and NMRcManager are its
	// DnsManager's Mode and RcManager properties.
	NetworkManager bool
	NMMode         string
	NMRcManager    string
	// Networkd: systemd-networkd runs.
	Networkd bool
	// ResolvConf describes /etc/resolv.conf.
	ResolvConf ResolvConfInfo
	// LookupName is the name that resolved now ("" when none did), and
	// LookupErr why the last one failed.
	LookupName string
	LookupErr  error
	// Backup is the state of an earlier switch's backup ("" when there is
	// none): see Manifest.State.
	Backup string
}

// ResolvConfInfo describes /etc/resolv.conf.
type ResolvConfInfo struct {
	Exists  bool
	Symlink string // the link's target, "" for a regular file
	// GeneratedByNM: a regular file whose first line is NetworkManager's
	// "# Generated by NetworkManager".
	GeneratedByNM bool
}

// The packages Check looks at.
const (
	PackageResolved   = "systemd-resolved"
	packageResolvconf = "resolvconf"
	packageOpenresolv = "openresolv"
)

// watchedPackages are the packages Gather asks dpkg about.
var watchedPackages = []string{PackageResolved, packageResolvconf, packageOpenresolv}

// Verdict is Check's answer.
type Verdict struct {
	// OK: the setup is supported, so Enable may run.
	OK bool
	// Problems say, one sentence each, what doesn't fit. Empty when OK.
	Problems []string
	// Manual says how to switch by hand instead, when it doesn't fit.
	Manual string
}

// Text is the verdict for a dialog or a notification.
func (v Verdict) Text() string {
	if v.OK {
		return "This computer's setup is supported."
	}
	var b strings.Builder
	b.WriteString("Penguintier can't switch this computer to systemd-resolved safely, so it changed nothing:\n")
	for _, p := range v.Problems {
		b.WriteString("• " + p + "\n")
	}
	if v.Manual != "" {
		b.WriteString("\n" + v.Manual)
	}
	return strings.TrimRight(b.String(), "\n")
}

// Check decides whether the setup is one Enable supports: the one it was
// built and tested for (a Debian-family system where NetworkManager writes
// /etc/resolv.conf). For anything else it returns the reasons; changing
// DNS on a setup we don't understand could cut the computer off.
//
// It does no I/O, so it is easy to test.
func Check(f Facts) Verdict {
	var problems []string
	add := func(format string, args ...any) {
		problems = append(problems, fmt.Sprintf(format, args...))
	}

	if f.OSFamily != "debian" {
		name := f.OSName
		if name == "" {
			name = "this system"
		}
		add("%s is not a Debian-family system (only those are supported for now).", name)
	}
	if !f.SystemdPID1 {
		add("systemd is not the init system.")
	}
	if !f.AptAvailable {
		add("apt-get or dpkg is missing.")
	}
	switch state := f.Packages[PackageResolved]; {
	case state == "installed":
		add("systemd-resolved is installed already.")
	case f.ResolvedRunning:
		add("systemd-resolved is running already.")
	}
	for _, p := range []string{packageResolvconf, packageOpenresolv} {
		if f.Packages[p] == "installed" {
			add("%s is installed; it also manages /etc/resolv.conf.", p)
		}
	}
	switch {
	case !f.NetworkManager:
		add("NetworkManager is not running.")
	case f.NMMode != "default" || f.NMRcManager != "symlink":
		add("NetworkManager's DNS setup is not the usual one (mode %q, rc-manager %q; expected \"default\" and \"symlink\").",
			f.NMMode, f.NMRcManager)
	}
	if f.Networkd {
		add("systemd-networkd is running.")
	}
	switch rc := f.ResolvConf; {
	case !rc.Exists:
		add("/etc/resolv.conf does not exist.")
	case rc.Symlink != "":
		add("/etc/resolv.conf is a link to %s, so something else manages it.", rc.Symlink)
	case !rc.GeneratedByNM:
		add("/etc/resolv.conf was not written by NetworkManager (edited by hand?).")
	}
	if f.LookupName == "" {
		reason := ""
		if f.LookupErr != nil {
			reason = " (" + f.LookupErr.Error() + ")"
		}
		add("Name lookups don't work right now%s, so the switch could not be checked. Try again when online.", reason)
	}
	switch f.Backup {
	case StateInProgress, StateUndoFailed:
		add("An earlier switch did not finish. Undo it first: pkexec %s undo", HelperPath)
	case StateEnabled:
		add("DNS support was switched on before; undo that first: pkexec %s undo", HelperPath)
	}

	if len(problems) == 0 {
		return Verdict{OK: true}
	}
	return Verdict{
		Problems: problems,
		Manual: "To switch by hand, install systemd-resolved with your package manager, make sure " +
			"/etc/resolv.conf points to /run/systemd/resolve/stub-resolv.conf and that names still resolve, " +
			"and keep a copy of /etc/resolv.conf and /etc/nsswitch.conf first.",
	}
}
